  ADD CONSTRAINT perfiles_rol_check
  CHECK (rol = ANY (ARRAY['admin'::text, 'encargado'::text, 'produccion'::text]));

CREATE TABLE public.produccion_registros (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  panaderia_id bigint NOT NULL REFERENCES public.panaderias(id) ON DELETE RESTRICT,
  fecha_produccion date NOT NULL,
  pan_nombre text NOT NULL CHECK (length(btrim(pan_nombre)) BETWEEN 1 AND 120),
  cantidad integer NOT NULL CHECK (cantidad >= 0),
  observaciones text,
  usuario_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  registrado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX produccion_registros_panaderia_fecha_idx
  ON public.produccion_registros (panaderia_id, fecha_produccion, registrado_en);

CREATE INDEX produccion_registros_usuario_idx
  ON public.produccion_registros (usuario_id, registrado_en);

