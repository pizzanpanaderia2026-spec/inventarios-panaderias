create table if not exists public.configuracion_archivado (
    id smallint primary key default 1 check (id = 1),
    dia_mes smallint not null default 15 check (dia_mes between 1 and 31),
    periodo_inicio date not null,
    periodo_fin date not null,
    desplazamiento_fin smallint not null default -1 check (desplazamiento_fin in (-1, 0)),
    ultima_ejecucion timestamptz,
    ultimo_error text,
    ultimo_error_en timestamptz,
    actualizado_por uuid references auth.users(id),
    actualizado_en timestamptz not null default now(),
    constraint configuracion_archivado_rango_valido check (periodo_fin >= periodo_inicio)
);

create table if not exists public.archivos_archivados (
    id bigint generated by default as identity primary key,
    panaderia_id bigint not null references public.panaderias(id),
    periodo_inicio date not null,
    periodo_fin date not null,
    archive_key text not null unique,
    estado text not null default 'pendiente'
        check (estado in ('pendiente', 'verificado', 'error')),
    drive_file_id text,
    drive_file_name text,
    sha256 text,
    tamano_bytes bigint,
    intentos integer not null default 0,
    ultimo_error text,
    verificado_en timestamptz,
    creado_en timestamptz not null default now(),
    actualizado_en timestamptz not null default now(),
    constraint archivos_archivados_rango_valido check (periodo_fin >= periodo_inicio),
    constraint archivos_archivados_periodo_local_unico
        unique (panaderia_id, periodo_inicio, periodo_fin)
);

create index if not exists idx_archivos_archivados_local_periodo
    on public.archivos_archivados (panaderia_id, periodo_inicio desc);

alter table public.configuracion_archivado enable row level security;
alter table public.archivos_archivados enable row level security;

revoke all privileges on table public.configuracion_archivado from anon, authenticated;
revoke all privileges on table public.archivos_archivados from anon, authenticated;
grant all privileges on table public.configuracion_archivado to service_role;
grant all privileges on table public.archivos_archivados to service_role;
grant usage, select on sequence public.archivos_archivados_id_seq to service_role;
