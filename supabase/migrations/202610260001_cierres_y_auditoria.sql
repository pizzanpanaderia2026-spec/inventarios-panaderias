create table if not exists public.cierres_diarios (
  id bigint generated by default as identity primary key,
  panaderia_id bigint not null references public.panaderias(id),
  fecha date not null,
  estado text not null default 'abierto' check (estado in ('abierto', 'cerrado')),
  cerrado_en timestamptz,
  cerrado_por uuid references auth.users(id),
  reabierto_en timestamptz,
  reabierto_por uuid references auth.users(id),
  motivo_correccion text,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  constraint cierres_diarios_panaderia_fecha_unica unique (panaderia_id, fecha)
);

alter table public.inventario_detalles
  add column if not exists cierre_id bigint references public.cierres_diarios(id),
  add column if not exists precio_unitario numeric(12,2);

create table if not exists public.auditoria_inventario (
  id bigint generated by default as identity primary key,
  cierre_id bigint references public.cierres_diarios(id),
  panaderia_id bigint not null references public.panaderias(id),
  usuario_id uuid references auth.users(id),
  accion text not null,
  motivo text,
  detalles jsonb not null default '{}'::jsonb,
  creado_en timestamptz not null default now()
);

-- Evita nombres duplicados dentro de la misma panadería (ignorando mayúsculas
-- y espacios exteriores). Si ya existen duplicados, este índice no se creará
-- hasta que se resuelvan manualmente; por eso debe revisarse antes de aplicar.
create unique index if not exists productos_panaderia_nombre_unico
  on public.productos (panaderia_id, lower(btrim(nombre)));

alter table public.cierres_diarios enable row level security;
alter table public.auditoria_inventario enable row level security;

