CREATE OR REPLACE FUNCTION public.registrar_venta_pos(
  p_panaderia_id bigint,
  p_fecha date,
  p_usuario_id uuid,
  p_usuario_nombre text,
  p_lineas jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_numero integer;
  v_venta_id bigint;
  v_total numeric(14,2) := 0;
  v_linea record;
  v_producto record;
  v_importe numeric(14,2);
  v_disponible boolean;
  v_cantidad_lineas integer := 0;
BEGIN
  IF p_lineas IS NULL OR jsonb_typeof(p_lineas) <> 'array'
     OR jsonb_array_length(p_lineas) < 1 OR jsonb_array_length(p_lineas) > 200 THEN
    RAISE EXCEPTION 'La venta debe contener al menos un producto.';
  END IF;

  IF (SELECT count(*) FROM jsonb_to_recordset(p_lineas) AS x(producto_id bigint, cantidad integer))
     <> (SELECT count(DISTINCT producto_id) FROM jsonb_to_recordset(p_lineas) AS x(producto_id bigint, cantidad integer)) THEN
    RAISE EXCEPTION 'No repitas productos en una misma venta.';
  END IF;

  -- Evita que dos cajeros reciban el mismo consecutivo para el mismo local y día.
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_panaderia_id::text || ':' || p_fecha::text, 0)
  );

  SELECT COALESCE(MAX(numero_venta), 0) + 1
    INTO v_numero
    FROM public.ventas_pos
   WHERE panaderia_id = p_panaderia_id AND fecha = p_fecha;

  INSERT INTO public.ventas_pos
    (panaderia_id, fecha, numero_venta, usuario_id, usuario_nombre, total)
  VALUES
    (p_panaderia_id, p_fecha, v_numero, p_usuario_id, COALESCE(NULLIF(btrim(p_usuario_nombre), ''), 'Usuario'), 0)
  RETURNING id INTO v_venta_id;

  FOR v_linea IN
    SELECT * FROM jsonb_to_recordset(p_lineas) AS x(producto_id bigint, cantidad integer)
  LOOP
    IF v_linea.cantidad IS NULL OR v_linea.cantidad < 1 OR v_linea.cantidad > 100000 THEN
      RAISE EXCEPTION 'La cantidad de cada producto debe ser mayor que cero.';
    END IF;

    SELECT id, nombre, precio
      INTO v_producto
      FROM public.productos
     WHERE id = v_linea.producto_id
       AND panaderia_id = p_panaderia_id
       AND activo IS TRUE
     FOR SHARE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Uno de los productos no existe o está desactivado.';
    END IF;

    SELECT disponible INTO v_disponible
      FROM public.disponibilidad_ventas
     WHERE panaderia_id = p_panaderia_id
       AND producto_id = v_linea.producto_id
       AND fecha = p_fecha
     FOR SHARE;

    IF NOT FOUND OR v_disponible IS NOT TRUE THEN
      RAISE EXCEPTION 'El producto no está disponible para venta hoy.';
    END IF;

    v_importe := round(v_producto.precio * v_linea.cantidad, 2);
    INSERT INTO public.ventas_pos_detalles
      (venta_id, producto_id, producto_nombre, cantidad, precio_unitario, importe)
    VALUES
      (v_venta_id, v_producto.id, v_producto.nombre, v_linea.cantidad, v_producto.precio, v_importe);

    v_total := v_total + v_importe;
    v_cantidad_lineas := v_cantidad_lineas + 1;
  END LOOP;

  UPDATE public.ventas_pos SET total = v_total WHERE id = v_venta_id;

  RETURN jsonb_build_object(
    'id', v_venta_id,
    'numero_venta', v_numero,
    'fecha', p_fecha,
    'total', v_total,
    'usuario_nombre', COALESCE(NULLIF(btrim(p_usuario_nombre), ''), 'Usuario'),
    'lineas', v_cantidad_lineas
  );
END;
$$;

REVOKE ALL ON FUNCTION public.registrar_venta_pos(bigint, date, uuid, text, jsonb) FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.registrar_venta_pos(bigint, date, uuid, text, jsonb) TO service_role;
