-- Punto de venta, permisos flexibles por módulo y personalización de colores.
-- Las ventas conservan nombre y precio históricos; la disponibilidad se reinicia
-- de forma natural al consultar una fecha nueva (sin borrar ventas anteriores).

ALTER TABLE public.perfiles
  ADD COLUMN IF NOT EXISTS permisos text[];

UPDATE public.perfiles
SET permisos = CASE
  WHEN es_admin_principal IS TRUE THEN ARRAY['inventarios','produccion','ventas']::text[]
  WHEN rol = 'produccion' THEN ARRAY['produccion']::text[]
  ELSE ARRAY['inventarios']::text[]
END
WHERE permisos IS NULL OR cardinality(permisos) = 0;

ALTER TABLE public.perfiles
  ALTER COLUMN permisos SET DEFAULT ARRAY['inventarios']::text[],
  ALTER COLUMN permisos SET NOT NULL;

CREATE TABLE IF NOT EXISTS public.configuracion_colores (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  ventas text NOT NULL DEFAULT '#2563EB' CHECK (ventas ~ '^#[0-9A-Fa-f]{6}$'),
  produccion text NOT NULL DEFAULT '#16A34A' CHECK (produccion ~ '^#[0-9A-Fa-f]{6}$'),
  inventarios text NOT NULL DEFAULT '#D97706' CHECK (inventarios ~ '^#[0-9A-Fa-f]{6}$'),
  actualizado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  actualizado_en timestamptz NOT NULL DEFAULT now()
);
INSERT INTO public.configuracion_colores (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.disponibilidad_ventas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  panaderia_id bigint NOT NULL REFERENCES public.panaderias(id) ON DELETE CASCADE,
  producto_id bigint NOT NULL REFERENCES public.productos(id) ON DELETE CASCADE,
  fecha date NOT NULL,
  disponible boolean NOT NULL DEFAULT false,
  actualizado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  UNIQUE (panaderia_id, fecha, producto_id)
);
CREATE INDEX IF NOT EXISTS disponibilidad_ventas_fecha_idx
  ON public.disponibilidad_ventas (panaderia_id, fecha, disponible);

CREATE TABLE IF NOT EXISTS public.ventas_pos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  panaderia_id bigint NOT NULL REFERENCES public.panaderias(id) ON DELETE RESTRICT,
  fecha date NOT NULL,
  numero_venta integer NOT NULL CHECK (numero_venta > 0),
  usuario_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  usuario_nombre text NOT NULL,
  total numeric(14,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  creado_en timestamptz NOT NULL DEFAULT now(),
  UNIQUE (panaderia_id, fecha, numero_venta)
);
CREATE INDEX IF NOT EXISTS ventas_pos_fecha_idx
  ON public.ventas_pos (panaderia_id, fecha, numero_venta);

CREATE TABLE IF NOT EXISTS public.ventas_pos_detalles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id bigint NOT NULL REFERENCES public.ventas_pos(id) ON DELETE CASCADE,
  producto_id bigint REFERENCES public.productos(id) ON DELETE SET NULL,
  producto_nombre text NOT NULL,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  precio_unitario numeric(12,2) NOT NULL CHECK (precio_unitario >= 0),
  importe numeric(14,2) NOT NULL CHECK (importe >= 0)
);
CREATE INDEX IF NOT EXISTS ventas_pos_detalles_venta_idx
  ON public.ventas_pos_detalles (venta_id);

ALTER TABLE public.configuracion_colores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.disponibilidad_ventas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ventas_pos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ventas_pos_detalles ENABLE ROW LEVEL SECURITY;

